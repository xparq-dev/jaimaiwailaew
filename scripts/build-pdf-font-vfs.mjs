import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);
const fontDirectory = path.join(projectRoot, "src", "pdf", "fonts");
const outputFile = path.join(fontDirectory, "sarabun-vfs.ts");
const fontFiles = [
  "Sarabun-Regular.ttf",
  "Sarabun-SemiBold.ttf",
  "Sarabun-Italic.ttf",
  "Sarabun-SemiBoldItalic.ttf",
];

const entries = await Promise.all(
  fontFiles.map(async (fileName) => [
    fileName,
    (await readFile(path.join(fontDirectory, fileName))).toString("base64"),
  ]),
);

const output = `// Generated by scripts/build-pdf-font-vfs.mjs. Do not edit manually.\nexport const sarabunVfs = ${JSON.stringify(Object.fromEntries(entries), null, 2)} as const;\n`;

await writeFile(outputFile, output, "utf8");
